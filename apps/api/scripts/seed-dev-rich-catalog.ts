export const DEV_RICH_CATALOG_LOCATIONS = [
  ...DEV_RICH_HIKING_LOCATIONS,
  ...DEV_RICH_CAMPING_LOCATIONS,
];

export type DevRichCatalogUpsert = (
  id: string,
  data: LocationCreateInput
) => Promise<unknown>;

/** Idempotent upsert via shared seed helper or inline write. */
export const seedDevRichCatalog = async (
  upsert?: DevRichCatalogUpsert
): Promise<{ upserted: number; hiking: number; camping: number }> => {
  let upserted = 0;

  const write = async (id: string, data: LocationCreateInput) => {
    if (upsert) {
      await upsert(id, data);
      upserted += 1;
      return;
    }
    const existing = await findLocationInMongo(id);
    let location = buildLocationFromCreateInput({ ...data, status: LocationStatus.ACTIVE }, id);
    if (existing?.createdAt) {
      location.createdAt = existing.createdAt;
    }
    location = await stampLocationGroupRegionLevels(location);
    await writeLocationToMongo(location);
    upserted += 1;
  };

  for (const row of DEV_RICH_CATALOG_LOCATIONS) {
    await write(row.id, row.data);
  }

  return {
    upserted,
    hiking: DEV_RICH_HIKING_LOCATIONS.length,
    camping: DEV_RICH_CAMPING_LOCATIONS.length,
  };
};
